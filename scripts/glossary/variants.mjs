/**
 * 四库全书异体字表：源文本字形 → 通行字形。
 *
 * 维基文库的 `variant=zh-hans` 会处理标准繁体（護→护、寶→宝、錄→录），但**不处理**
 * 四库本里的异体写法。实测漏掉 `徳`(U+5FB3) 会把神煞名覆盖率从 147 掉到 141——
 * 「月德合 / 天德合 / 阴德 / 阳德 / 时德」全部匹配不上，因为原文写的是 `月徳合`。
 *
 * 键是异体写法，值是通行写法。只收录字形等价、不改变字义的对应，
 * 避免制造出假匹配。
 *
 * 这张表**只做四库字形归一，不是简繁转换器**。别拿它去把简体文案转成繁体：简转繁有一简对多繁
 * 的问题（「历」在「万年历」应作「曆」，「日历」才是「歷」；复/復/複、发/發/髮同理），
 * 一对一的映射表在这里必然出错，得逐条写。
 */
export const VARIANTS = {
  徳: '德', // U+5FB3，和製/朝鮮汉字形的「德」
  䕶: '护', // U+4576
  寳: '宝', // U+5BF3
  冨: '富', // U+51A8
  㐫: '凶', // U+341B
  兎: '兔', // U+514E
  塟: '葬', // U+585F
  寛: '宽', // U+5BDB
  眞: '真', // U+771E
  敎: '教', // U+654E
  甯: '宁', // U+752F
  歩: '步', // U+6B69
  熈: '熙', // U+7188
  煕: '熙', // U+7155
  煖: '暖' // U+7156
}

/** 把文本里的四库异体字替换成通行字形。 */
export function normalizeVariants(text) {
  let out = text
  for (const [from, to] of Object.entries(VARIANTS)) out = out.split(from).join(to)
  return out
}
